#!/usr/bin/env node
// Fails (exit 1) when any source under web/apps or web/packages spells a colour
// instead of using the design tokens. Usage:
//   node scripts/check-colors.mjs            scan everything
//   node scripts/check-colors.mjs FILE...    scan only these files (pre-commit)
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { findColors } from './check-colors-lib.mjs';

const webRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const EXTS = new Set(['.ts', '.tsx', '.js', '.mjs', '.cjs', '.jsx', '.css', '.mdx', '.md', '.json', '.svg']);
const SKIP_DIRS = new Set([
  'node_modules', '.next', '.open-next', '.turbo', '.wrangler', '.source', '.git',
  'dist', 'build', 'out', 'coverage', 'generated',
]);
// The only literal-colour source of truth.
const EXEMPT = new Set(['packages/ui/src/styles/tokens.css']);
const GENERATED_FILE = /(\.generated\.|pnpm-lock|package-lock|cloudflare-env\.d\.ts$)/;

function skipFile(rel) {
  if (EXEMPT.has(rel) || GENERATED_FILE.test(rel)) return true;
  const parts = rel.split('/');
  if (!(parts[0] === 'apps' || parts[0] === 'packages')) return true;
  if (parts.some((p) => SKIP_DIRS.has(p))) return true;
  return !EXTS.has(rel.slice(rel.lastIndexOf('.')));
}

function walk(dir, out) {
  for (const name of readdirSync(dir)) {
    if (SKIP_DIRS.has(name)) continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else out.push(p);
  }
}

const files = process.argv.slice(2).map((f) => resolve(f));
if (files.length === 0) for (const d of ['apps', 'packages']) walk(join(webRoot, d), files);

let count = 0;
for (const abs of files) {
  const rel = relative(webRoot, abs).split(sep).join('/');
  if (skipFile(rel)) continue;
  let text;
  try {
    text = readFileSync(abs, 'utf8');
  } catch {
    continue;
  }
  // Derived from tokens.css by scripts/gen-tokens.mjs (drift-checked in CI).
  if (text.slice(0, 200).includes('GENERATED by scripts/gen-tokens.mjs')) continue;
  for (const f of findColors(text, rel)) {
    count++;
    console.log(`web/${rel}:${f.line}:${f.col}  ${f.text}  [${f.rule}]`);
  }
}
if (count > 0) {
  console.error(
    `\ncheck:colors: ${count} hard-coded colour(s). Use var(--token) or a token Tailwind class ` +
      `(see packages/ui/src/styles/tokens.css); non-CSS contexts derive from the generated tokens module.`,
  );
  process.exit(1);
}
console.log('check:colors: ok (token-only colours)');
