#!/usr/bin/env node
// Derives apps/web/lib/generated/tokens.ts from packages/ui/src/styles/tokens.css,
// the single source of truth for colours. For contexts that cannot read CSS
// variables (next/og ImageResponse, <meta name="theme-color">, the PWA
// manifest, the standalone global-error document, the SVG icon).
//   node scripts/gen-tokens.mjs          write the module
//   node scripts/gen-tokens.mjs --check  fail if the committed module is stale
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const webRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = resolve(webRoot, 'packages/ui/src/styles/tokens.css');
const out = resolve(webRoot, 'apps/web/lib/generated/tokens.ts');

/** Declarations of the first `selector { ... }` block (no nesting in tokens.css). */
function block(css, selector) {
  const m = css.match(new RegExp(`(?:^|\\n)${selector.replace('.', '\\.')}\\s*\\{([^}]*)\\}`));
  if (!m) throw new Error(`tokens.css: block ${selector} not found`);
  const vars = {};
  for (const d of m[1].matchAll(/--([\w-]+)\s*:\s*([^;]+);/g)) vars[d[1]] = d[2].trim();
  return vars;
}

function oklchToSrgb(l, c, h) {
  const hr = (h * Math.PI) / 180;
  const a = c * Math.cos(hr);
  const b = c * Math.sin(hr);
  const l_ = (l + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m_ = (l - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s_ = (l - 0.0894841775 * a - 1.291485548 * b) ** 3;
  const lin = [
    4.0767416621 * l_ - 3.3077115913 * m_ + 0.2309699292 * s_,
    -1.2684380046 * l_ + 2.6097574011 * m_ - 0.3413193965 * s_,
    -0.0041960863 * l_ - 0.7034186147 * m_ + 1.707614701 * s_,
  ];
  return lin.map((v) => {
    const x = Math.min(1, Math.max(0, v));
    const g = x <= 0.0031308 ? 12.92 * x : 1.055 * x ** (1 / 2.4) - 0.055;
    return Math.round(g * 255);
  });
}

function toHex(value) {
  const m = value.match(/^oklch\(\s*([\d.]+)\s+([\d.]+)\s+([\d.]+)\s*(?:\/\s*([\d.]+))?\s*\)$/);
  if (!m) throw new Error(`tokens.css: unsupported colour value "${value}"`);
  const [r, g, b] = oklchToSrgb(+m[1], +m[2], +m[3]);
  const hex = [r, g, b].map((n) => n.toString(16).padStart(2, '0')).join('');
  return `#${hex}${m[4] !== undefined ? Math.round(+m[4] * 255).toString(16).padStart(2, '0') : ''}`;
}

function resolveAll(vars) {
  const res = {};
  const get = (k, seen = []) => {
    const v = vars[k];
    if (v === undefined) throw new Error(`tokens.css: unknown token --${k}`);
    const ref = v.match(/^var\(--([\w-]+)\)$/);
    if (ref) return seen.includes(ref[1]) ? (() => { throw new Error('cycle'); })() : get(ref[1], [...seen, k]);
    return v;
  };
  for (const k of Object.keys(vars)) {
    if (k === 'radius') continue;
    const v = get(k);
    if (!v.startsWith('oklch(')) continue; // non-colour (color-scheme etc.)
    res[k] = toHex(v);
  }
  return res;
}

const css = readFileSync(src, 'utf8');
const light = block(css, ':root');
const dark = { ...light, ...block(css, '.dark') };
// `.dark` inherits :root; aliases like --diff-add resolve against the dark values.
const palettes = { light: resolveAll(light), dark: resolveAll(dark) };

const camel = (k) => k.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const body = (p) =>
  Object.entries(p)
    .map(([k, v]) => `    ${camel(k)}: '${v}',`)
    .join('\n');
const content = `// GENERATED by scripts/gen-tokens.mjs from packages/ui/src/styles/tokens.css.
// Do not edit; run \`pnpm gen:tokens\` after changing the tokens.
// sRGB hex equivalents for contexts that cannot read CSS variables.

export const tokens = {
  light: {
${body(palettes.light)}
  },
  dark: {
${body(palettes.dark)}
  },
} as const;

export type TokenName = keyof typeof tokens.light;
`;

const L = palettes.light;
const D = palettes.dark;
// Favicon: inverted foreground/background, flipped under prefers-color-scheme: dark.
const icon =
  `<!-- GENERATED by scripts/gen-tokens.mjs from tokens.css; do not edit (pnpm gen:tokens). -->\n` +
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32"><style>rect{fill:${L.foreground}}text{fill:${L.background}}@media (prefers-color-scheme: dark){rect{fill:${D.foreground}}text{fill:${D.background}}}</style><rect width="32" height="32" rx="3"/><text x="16" y="23.5" text-anchor="middle" font-family="ui-sans-serif,system-ui,-apple-system,Segoe UI,Helvetica,Arial,sans-serif" font-size="24" font-weight="600">a</text></svg>\n`;

const targets = [
  [out, content],
  [resolve(webRoot, 'apps/web/app/icon.svg'), icon],
];
if (process.argv.includes('--check')) {
  const stale = targets.filter(([p, c]) => !existsSync(p) || readFileSync(p, 'utf8') !== c);
  if (stale.length) {
    console.error('Generated token files are stale: run `pnpm gen:tokens` (from web/) and commit the result.');
    process.exit(1);
  }
  console.log('generated token files are up to date');
} else {
  mkdirSync(dirname(out), { recursive: true });
  for (const [p, c] of targets) writeFileSync(p, c);
  console.log('wrote generated token files');
}

