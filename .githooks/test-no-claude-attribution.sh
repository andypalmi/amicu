#!/bin/sh
# Unit-style tests for no-claude-attribution.sh. Run: sh .githooks/test-no-claude-attribution.sh
dir=$(cd "$(dirname "$0")" && pwd)
tmp=$(mktemp) || exit 2
fail=0

# expect <hit|ok> <text>
expect() {
  printf '%s\n' "$2" >"$tmp"
  if "$dir/no-claude-attribution.sh" check "$tmp" >/dev/null 2>&1; then got=ok; else got=hit; fi
  if [ "$got" != "$1" ]; then
    echo "FAIL (expected $1, got $got): $2"
    fail=1
  fi
}

expect hit 'Claude-Session: https://claude.ai/code/session_abc'
expect hit 'https://claude.ai/code/session_abc'
expect hit 'Co-Authored-By: Claude <noreply@anthropic.com>'
expect hit 'co-authored-by: Claude Opus 4.8 <x@y.z>'
expect hit 'Co-Authored-By: Anthropic bot'
expect hit 'Generated with [Claude Code](https://claude.com/claude-code)'
expect hit 'Generated with Claude'
expect hit '🤖 Generated by a tool'
expect hit 'noreply@anthropic.com'
expect hit 'written with Claude Code'
expect hit 'ask CLAUDE about it'
expect hit 'update CLAUDE.md and ask claude'
expect ok 'fix .claude/settings.json path'
expect ok 'update CLAUDE.md with new rules'
expect ok 'move .claude/worktrees/foo into ignore'
expect ok 'feat: add the thing'
expect ok 'Closes andypalmi/amicu-planning#191'

# comment lines are ignored
printf '# Claude Code was here\nfix: thing\n' >"$tmp"
"$dir/no-claude-attribution.sh" check "$tmp" >/dev/null 2>&1 || { echo "FAIL: comment line flagged"; fail=1; }

# strip removes only offending lines
printf 'fix: thing\n\nClaude-Session: https://claude.ai/code/session_x\n' >"$tmp"
"$dir/no-claude-attribution.sh" strip "$tmp" >/dev/null 2>&1 && { echo "FAIL: strip returned 0 on hit"; fail=1; }
[ "$(cat "$tmp")" = "fix: thing

" ] || [ "$(grep -c . "$tmp")" = 1 ] || { echo "FAIL: strip left offending line"; fail=1; }
grep -qi claude "$tmp" && { echo "FAIL: strip left Claude text"; fail=1; }

rm -f "$tmp"
[ "$fail" -eq 0 ] && echo "all tests passed"
exit "$fail"
