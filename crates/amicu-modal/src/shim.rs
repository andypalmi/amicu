//! The tiny Python module that Modal's container runtime imports.
//!
//! Modal's container entrypoint is Python: for a server Function it does
//! `importlib.import_module(function_def.module_name)` and then
//! `getattr(module, function_def.function_name)`
//! (`modal/_runtime/user_code_imports.py:517-532`), instantiates the class,
//! and drives its `@modal.enter` / `@modal.exit` lifecycle hooks
//! (`modal/_runtime/user_code_imports.py:593-640`). There is no way around
//! *some* Python existing inside the container.
//!
//! amicu never ships a `.py` file and never runs Python locally: this module
//! renders that class as a Rust string, which [`crate::ImageSpec`] bakes into
//! the container image at build time (base64-encoded, so no shell quoting is
//! involved). The process it launches is passed as a JSON literal, never
//! interpolated into a shell command line.
//!
//! The class is deliberately *undecorated*: `import_server_service` accepts a
//! plain class and synthesises an `_App` for it
//! (`modal/_runtime/user_code_imports.py:620-631`, `get_active_app_fallback`
//! at `:643-666`), so the shim needs neither a `modal.App` object nor the
//! `@app._experimental_server` decorator — only `modal.enter` / `modal.exit`,
//! which come from the `modal` package Modal mounts into the container at
//! runtime (see `crate::MODAL_CLIENT_MOUNT_NAME`).

/// The module name the container imports; [`SHIM_PATH`] is
/// `/root/<SHIM_MODULE_NAME>.py`, and `/root` is the container's working
/// directory, which CPython puts on `sys.path`.
pub const SHIM_MODULE_NAME: &str = "amicu_server";

/// Absolute path the shim is written to inside the image.
pub const SHIM_PATH: &str = "/root/amicu_server.py";

/// The class name inside the shim; this is the `function_name` that
/// `FunctionCreate`/`AppPublish` refer to and that the container resolves with
/// `getattr` (`modal/_runtime/user_code_imports.py:524-532`, which notes
/// "servers use `ClassName`").
pub const SHIM_CLASS_NAME: &str = "Server";

/// Renders the container-side Python module for a server that runs `argv` as a
/// subprocess listening on `port`.
///
/// `argv` is embedded as a double-encoded JSON literal: the argv list is
/// serialised to JSON, and that JSON *text* is serialised again as a JSON
/// string, which is always a valid Python string literal (`serde_json` only
/// emits `\"`, `\\`, `\n`, `\r`, `\t`, `\u00XX` escapes, all of which Python
/// understands identically). Nothing from `argv` reaches a shell.
///
/// `port` is load-bearing, not decoration: `@modal.enter` does not return
/// until the child process is accepting connections on it, and raises
/// immediately if the child exits first. Without that, a server that dies
/// during startup looks to Modal like a slow one, and the failure only
/// surfaces as an `http_config.startup_timeout` expiry with no cause attached.
#[must_use]
pub fn render_shim(argv: &[String], port: u16) -> String {
    let argv_json = serde_json::to_string(argv).expect("a Vec<String> always serialises");
    let argv_literal = serde_json::to_string(&argv_json).expect("a String always serialises");

    format!(
        "# Generated by amicu; do not edit.\n\
         import json\n\
         import socket\n\
         import subprocess\n\
         import time\n\
         \n\
         import modal\n\
         \n\
         ARGV = json.loads({argv_literal})\n\
         PORT = {port}\n\
         \n\
         \n\
         class {SHIM_CLASS_NAME}:\n\
         \x20   @modal.enter()\n\
         \x20   def start(self):\n\
         \x20       self.process = subprocess.Popen(ARGV)\n\
         \x20       while self.process.poll() is None:\n\
         \x20           with socket.socket() as probe:\n\
         \x20               if probe.connect_ex((\"127.0.0.1\", PORT)) == 0:\n\
         \x20                   return\n\
         \x20           time.sleep(1)\n\
         \x20       raise RuntimeError(\"server exited with %s\" % self.process.returncode)\n\
         \n\
         \x20   @modal.exit()\n\
         \x20   def stop(self):\n\
         \x20       self.process.terminate()\n\
         \x20       try:\n\
         \x20           self.process.wait(timeout=30)\n\
         \x20       except Exception:\n\
         \x20           self.process.kill()\n"
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    fn argv(parts: &[&str]) -> Vec<String> {
        parts.iter().map(|s| (*s).to_owned()).collect()
    }

    #[test]
    fn renders_a_short_module_with_no_placeholders_left() {
        let source = render_shim(&argv(&["python", "-m", "http.server", "8000"]), 8000);

        // No leftover `format!` placeholders of any shape.
        assert!(!source.contains('{') && !source.contains('}'), "{source}");
        assert!(source.contains("class Server:"));
        assert!(source.contains("@modal.enter()"));
        assert!(source.contains("@modal.exit()"));
        assert!(
            source.lines().count() <= 32,
            "shim must stay tiny, got {} lines",
            source.lines().count()
        );
    }

    #[test]
    fn the_port_is_used_by_the_readiness_probe_not_just_commented() {
        let source = render_shim(&argv(&["srv"]), 9123);
        assert!(source.contains("PORT = 9123\n"));
        assert!(source.contains(r#"probe.connect_ex(("127.0.0.1", PORT))"#));
        // And a child that dies during startup fails loudly rather than
        // silently burning the startup timeout.
        assert!(source.contains("raise RuntimeError"));
        assert!(!source.contains("9123."), "port is not left in a comment");
    }

    #[test]
    fn embeds_argv_as_a_json_literal_that_python_can_parse_back() {
        let source = render_shim(
            &argv(&["vllm", "serve", "Qwen/Qwen2.5-0.5B-Instruct"]),
            8000,
        );
        assert!(
            source.contains(
                r#"ARGV = json.loads("[\"vllm\",\"serve\",\"Qwen/Qwen2.5-0.5B-Instruct\"]")"#
            ),
            "unexpected argv literal in:\n{source}"
        );
    }

    #[test]
    fn escapes_quotes_spaces_and_backslashes_instead_of_shell_interpolating_them() {
        let nasty = argv(&[
            "serve",
            "--flag=a b",
            "he said \"hi\"",
            "back\\slash",
            "; rm -rf /",
            "$(whoami)",
        ]);
        let source = render_shim(&nasty, 8000);

        // The double encoding means every literal quote from argv appears as
        // `\\\"` in the rendered Python, never as a bare `"` that could end
        // the string, and shell metacharacters are inert text.
        let line = source
            .lines()
            .find(|l| l.starts_with("ARGV = "))
            .expect("argv line");
        assert!(line.contains(r"\\\"), "backslash survived escaping: {line}");
        assert!(line.contains(r#"he said \\\"hi\\\""#), "{line}");
        assert!(line.contains("; rm -rf /"), "{line}");
        assert!(line.contains("$(whoami)"), "{line}");
        assert!(line.ends_with(')'), "argv stays on one line: {line}");
        assert_eq!(
            source.lines().filter(|l| l.starts_with("ARGV = ")).count(),
            1
        );

        // And the literal is a valid JSON string whose contents are the
        // original argv, i.e. `json.loads` recovers it byte for byte.
        let literal = line
            .trim_start_matches("ARGV = json.loads(")
            .trim_end_matches(')');
        let inner: String = serde_json::from_str(literal).expect("valid JSON string literal");
        let decoded: Vec<String> = serde_json::from_str(&inner).expect("valid JSON array");
        assert_eq!(decoded, nasty);
    }
}
